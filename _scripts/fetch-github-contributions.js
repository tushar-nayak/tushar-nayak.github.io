const fs = require("fs");
const path = require("path");
const https = require("https");

const username = process.argv[2] || process.env.GITHUB_CONTRIB_USER || "tushar-nayak";
const endpoint = `https://github.com/users/${username}/contributions`;
const outputPath = path.join(__dirname, "..", "_includes", "generated", "github_contributions.liquid");

function request(url, redirects = 0) {
  return new Promise((resolve, reject) => {
    https
      .get(
        url,
        {
          headers: {
            "User-Agent": "tushar-nayak.github.io contribution sync",
            Accept: "text/html",
          },
        },
        (response) => {
          const status = response.statusCode || 0;

          if (status >= 300 && status < 400 && response.headers.location) {
            if (redirects > 5) {
              reject(new Error(`Too many redirects while fetching ${url}`));
              return;
            }

            const redirectedUrl = new URL(response.headers.location, url).toString();
            response.resume();
            resolve(request(redirectedUrl, redirects + 1));
            return;
          }

          if (status < 200 || status >= 300) {
            reject(new Error(`GitHub contributions request failed with HTTP ${status}`));
            response.resume();
            return;
          }

          let body = "";
          response.setEncoding("utf8");
          response.on("data", (chunk) => {
            body += chunk;
          });
          response.on("end", () => resolve(body));
        }
      )
      .on("error", reject);
  });
}

function normalizeMarkup(markup) {
  return markup
    .trim()
    .replace(
      /<a href="https:\/\/docs\.github\.com\/articles\/why-are-my-contributions-not-showing-up-on-my-profile" class="Link--muted">/g,
      '<a href="https://docs.github.com/articles/why-are-my-contributions-not-showing-up-on-my-profile" class="Link--muted" target="_blank" rel="noopener noreferrer">'
    );
}

async function main() {
  const html = await request(endpoint);
  const normalized = normalizeMarkup(html);

  fs.mkdirSync(path.dirname(outputPath), { recursive: true });
  fs.writeFileSync(
    outputPath,
    `<!-- Generated by _scripts/fetch-github-contributions.js for ${username}. -->\n${normalized}\n`,
    "utf8"
  );

  process.stdout.write(`Saved GitHub contributions markup to ${outputPath}\n`);
}

main().catch((error) => {
  process.stderr.write(`${error.message}\n`);
  process.exit(1);
});
